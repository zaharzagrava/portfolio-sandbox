import { z } from 'zod';

/**
 * What is sealed in `Integration.credentialsSealed` (FR-007). Never logged, never returned by the API. The provider is
 * part of the value so a row can never be opened with the wrong adapter.
 */
const shopifyCredentialsSchema = z.object({
  provider: z.literal('shopify'),
  accessToken: z.string().min(1),
  refreshToken: z.string().min(1).optional(),
  /** ISO time the access token expires (offline expiring tokens). */
  expiresAt: z.string().optional(),
  scope: z.string(),
});

const wooCredentialsSchema = z.object({
  provider: z.literal('woocommerce'),
  consumerKey: z.string().min(1),
  consumerSecret: z.string().min(1),
  /** Generated by the platform at connect time; the provider signs its deliveries with it. */
  webhookSecret: z.string().min(1),
});

export const storedCredentialsSchema = z.discriminatedUnion('provider', [
  shopifyCredentialsSchema,
  wooCredentialsSchema,
]);

export type StoredCredentials = z.infer<typeof storedCredentialsSchema>;
export type ShopifyCredentials = z.infer<typeof shopifyCredentialsSchema>;
export type WooCredentials = z.infer<typeof wooCredentialsSchema>;

export const serialiseCredentials = (c: StoredCredentials): string =>
  JSON.stringify(storedCredentialsSchema.parse(c));

export const parseCredentials = (plaintext: string): StoredCredentials =>
  storedCredentialsSchema.parse(JSON.parse(plaintext));
